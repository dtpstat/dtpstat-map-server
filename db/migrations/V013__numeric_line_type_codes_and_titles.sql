SET SEARCH_PATH = BUSLANES, PUBLIC;

-- V008 used CODE as a textual import key and NAME as the legend label.
-- Preserve both meanings while moving to the final model:
--   CODE  - numeric DB-generated portable code
--   NAME  - immutable/imported source name
--   TITLE - editable human-readable legend label

DO $MIGRATION$
DECLARE
    DUPLICATES TEXT;
BEGIN
    SELECT STRING_AGG(FORMAT('%s (%s)', NORMALIZED_NAME, ROW_COUNT), ', ' ORDER BY NORMALIZED_NAME)
    INTO DUPLICATES
    FROM (
        SELECT LOWER(BTRIM(CODE)) AS NORMALIZED_NAME, COUNT(*) AS ROW_COUNT
        FROM BUSLANES.LINE_TYPES
        GROUP BY LOWER(BTRIM(CODE))
        HAVING COUNT(*) > 1
    ) AS DUPLICATE_NAMES;

    IF DUPLICATES IS NOT NULL THEN
        RAISE EXCEPTION 'Cannot migrate line type import names; textual codes duplicate ignoring case/outer spaces: %', DUPLICATES;
    END IF;
END
$MIGRATION$;

ALTER TABLE BUSLANES.LINE_TYPES
    ADD COLUMN IF NOT EXISTS TITLE TEXT;

UPDATE BUSLANES.LINE_TYPES
SET TITLE = BTRIM(NAME)
WHERE TITLE IS NULL;

DROP INDEX IF EXISTS BUSLANES.LINE_TYPES_NAME_CI_UIDX;

ALTER TABLE BUSLANES.LINE_TYPES
    DROP CONSTRAINT IF EXISTS LINE_TYPES_CODE_CHECK,
    DROP CONSTRAINT IF EXISTS LINE_TYPES_CODE_KEY;

ALTER TABLE BUSLANES.LINE_TYPES
    RENAME COLUMN CODE TO LEGACY_CODE;

UPDATE BUSLANES.LINE_TYPES
SET NAME = BTRIM(LEGACY_CODE),
    TITLE = BTRIM(TITLE),
    UPDATED_AT = NOW();

CREATE SEQUENCE IF NOT EXISTS BUSLANES.LINE_TYPES_CODE_SEQ
    AS INTEGER
    MINVALUE 1
    START WITH 1;

ALTER TABLE BUSLANES.LINE_TYPES
    ADD COLUMN CODE INTEGER;

UPDATE BUSLANES.LINE_TYPES
SET CODE = 0
WHERE LEGACY_CODE = 'default';

UPDATE BUSLANES.LINE_TYPES
SET CODE = NEXTVAL('BUSLANES.LINE_TYPES_CODE_SEQ')
WHERE CODE IS NULL;

ALTER TABLE BUSLANES.LINE_TYPES
    ALTER COLUMN CODE SET DEFAULT NEXTVAL('BUSLANES.LINE_TYPES_CODE_SEQ'),
    ALTER COLUMN CODE SET NOT NULL,
    ALTER COLUMN TITLE SET NOT NULL,
    ADD CONSTRAINT LINE_TYPES_CODE_KEY UNIQUE (CODE),
    ADD CONSTRAINT LINE_TYPES_CODE_CHECK CHECK (CODE >= 0),
    ADD CONSTRAINT LINE_TYPES_TITLE_CHECK CHECK (
        LENGTH(BTRIM(TITLE)) BETWEEN 1 AND 120
        AND TITLE = BTRIM(TITLE)
    );

ALTER SEQUENCE BUSLANES.LINE_TYPES_CODE_SEQ
    OWNED BY BUSLANES.LINE_TYPES.CODE;

SELECT SETVAL(
    'BUSLANES.LINE_TYPES_CODE_SEQ',
    GREATEST(COALESCE(MAX(CODE), 0) + 1, 1),
    FALSE
)
FROM BUSLANES.LINE_TYPES;

CREATE UNIQUE INDEX LINE_TYPES_NAME_CI_UIDX
    ON BUSLANES.LINE_TYPES (LOWER(BTRIM(NAME)));

ALTER TABLE BUSLANES.LINE_TYPES
    DROP COLUMN LEGACY_CODE;

COMMENT ON COLUMN BUSLANES.LINE_TYPES.CODE IS
    'Numeric business type code generated by the database. It is portable data, not a user-entered label.';
COMMENT ON COLUMN BUSLANES.LINE_TYPES.NAME IS
    'Imported source type name; unique ignoring case and leading/trailing spaces.';
COMMENT ON COLUMN BUSLANES.LINE_TYPES.TITLE IS
    'Human-readable legend title editable in the admin UI.';
