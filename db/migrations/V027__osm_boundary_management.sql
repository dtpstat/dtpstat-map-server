CREATE OR REPLACE FUNCTION BUSLANES.REBUILD_CITY_BOUNDARY_HIERARCHY()
RETURNS VOID
LANGUAGE PLPGSQL
AS $FUNCTION$
BEGIN
    UPDATE BUSLANES.CITY_BOUNDARIES
    SET AREA_M2 = ST_AREA(GEOM::GEOGRAPHY);

    UPDATE BUSLANES.CITY_BOUNDARIES AS CHILD
    SET PARENT_ID = (
        SELECT PARENT.ID
        FROM BUSLANES.CITY_BOUNDARIES AS PARENT
        WHERE PARENT.ID <> CHILD.ID
          AND PARENT.GEOM && CHILD.GEOM
          AND PARENT.AREA_M2 > CHILD.AREA_M2
          AND NOT ST_EQUALS(PARENT.GEOM, CHILD.GEOM)
          AND ST_COVERS(PARENT.GEOM, CHILD.GEOM)
        ORDER BY PARENT.AREA_M2, PARENT.ID
        LIMIT 1
    );
END
$FUNCTION$;

CREATE OR REPLACE FUNCTION BUSLANES.SYNC_ACTIVE_BOUNDARY_CITIES()
RETURNS VOID
LANGUAGE PLPGSQL
AS $FUNCTION$
BEGIN
    -- If an active boundary identity changes, release its stale application
    -- city link so the normalized type/name can be resolved again.
    UPDATE BUSLANES.CITY_BOUNDARIES AS BOUNDARY
    SET CITY_ID = NULL,
        UPDATED_AT = NOW()
    FROM BUSLANES.CITIES AS CITY
    WHERE BOUNDARY.IS_ACTIVE
      AND BOUNDARY.CITY_ID = CITY.ID
      AND (
        LOWER(REGEXP_REPLACE(CITY.DISPLAY_TYPE, '[[:space:]]+', '', 'g'))
            <> LOWER(REGEXP_REPLACE(BOUNDARY.DISPLAY_TYPE, '[[:space:]]+', '', 'g'))
        OR LOWER(REGEXP_REPLACE(CITY.NAME, '[[:space:]]+', '', 'g'))
            <> LOWER(REGEXP_REPLACE(BOUNDARY.DISPLAY_NAME, '[[:space:]]+', '', 'g'))
      );

    -- CITIES is storage, not the uniqueness authority. Reuse the oldest
    -- compatible row if legacy data contains equivalent normalized identities.
    UPDATE BUSLANES.CITY_BOUNDARIES AS BOUNDARY
    SET CITY_ID = (
            SELECT CITY.ID
            FROM BUSLANES.CITIES AS CITY
            WHERE LOWER(REGEXP_REPLACE(CITY.DISPLAY_TYPE, '[[:space:]]+', '', 'g'))
                  = LOWER(REGEXP_REPLACE(BOUNDARY.DISPLAY_TYPE, '[[:space:]]+', '', 'g'))
              AND LOWER(REGEXP_REPLACE(CITY.NAME, '[[:space:]]+', '', 'g'))
                  = LOWER(REGEXP_REPLACE(BOUNDARY.DISPLAY_NAME, '[[:space:]]+', '', 'g'))
            ORDER BY CITY.ID
            LIMIT 1
        ),
        UPDATED_AT = NOW()
    WHERE BOUNDARY.IS_ACTIVE
      AND BOUNDARY.CITY_ID IS NULL
      AND EXISTS (
            SELECT 1
            FROM BUSLANES.CITIES AS CITY
            WHERE LOWER(REGEXP_REPLACE(CITY.DISPLAY_TYPE, '[[:space:]]+', '', 'g'))
                  = LOWER(REGEXP_REPLACE(BOUNDARY.DISPLAY_TYPE, '[[:space:]]+', '', 'g'))
              AND LOWER(REGEXP_REPLACE(CITY.NAME, '[[:space:]]+', '', 'g'))
                  = LOWER(REGEXP_REPLACE(BOUNDARY.DISPLAY_NAME, '[[:space:]]+', '', 'g'))
        );

    INSERT INTO BUSLANES.CITIES (
        SLUG,
        NAME,
        FULL_NAME,
        DISPLAY_TYPE,
        LANE_LENGTH_M,
        ATTRIBUTES
    )
    SELECT
        'osm-' || BOUNDARY.OSM_TYPE || '-' || BOUNDARY.OSM_ID,
        BOUNDARY.DISPLAY_NAME,
        BOUNDARY.DISPLAY_NAME,
        BOUNDARY.DISPLAY_TYPE,
        0,
        JSONB_BUILD_OBJECT(
            '_osm',
            JSONB_BUILD_OBJECT(
                'osmType', BOUNDARY.OSM_TYPE,
                'osmId', BOUNDARY.OSM_ID,
                'placeType', BOUNDARY.PLACE_TYPE,
                'adminLevel', BOUNDARY.ADMIN_LEVEL
            )
        )
    FROM BUSLANES.CITY_BOUNDARIES AS BOUNDARY
    WHERE BOUNDARY.IS_ACTIVE
      AND BOUNDARY.CITY_ID IS NULL
    ON CONFLICT (SLUG) DO UPDATE SET
        NAME = EXCLUDED.NAME,
        FULL_NAME = EXCLUDED.FULL_NAME,
        DISPLAY_TYPE = EXCLUDED.DISPLAY_TYPE,
        ATTRIBUTES = BUSLANES.CITIES.ATTRIBUTES || EXCLUDED.ATTRIBUTES,
        UPDATED_AT = NOW();

    UPDATE BUSLANES.CITY_BOUNDARIES AS BOUNDARY
    SET CITY_ID = CITY.ID,
        UPDATED_AT = NOW()
    FROM BUSLANES.CITIES AS CITY
    WHERE BOUNDARY.IS_ACTIVE
      AND BOUNDARY.CITY_ID IS NULL
      AND CITY.SLUG = 'osm-' || BOUNDARY.OSM_TYPE || '-' || BOUNDARY.OSM_ID;

    UPDATE BUSLANES.CITIES AS CITY
    SET NAME = BOUNDARY.DISPLAY_NAME,
        FULL_NAME = BOUNDARY.DISPLAY_NAME,
        DISPLAY_TYPE = BOUNDARY.DISPLAY_TYPE,
        ATTRIBUTES = CITY.ATTRIBUTES || JSONB_BUILD_OBJECT(
            '_osm',
            JSONB_BUILD_OBJECT(
                'osmType', BOUNDARY.OSM_TYPE,
                'osmId', BOUNDARY.OSM_ID,
                'placeType', BOUNDARY.PLACE_TYPE,
                'adminLevel', BOUNDARY.ADMIN_LEVEL
            )
        ),
        UPDATED_AT = NOW()
    FROM BUSLANES.CITY_BOUNDARIES AS BOUNDARY
    WHERE BOUNDARY.CITY_ID = CITY.ID
      AND BOUNDARY.IS_ACTIVE;

    -- Line rows carry both boundary_id and city_id; keep city_id aligned after
    -- an active boundary is renamed or reassigned.
    UPDATE BUSLANES.CITY_GEOMETRIES AS GEOMETRY
    SET CITY_ID = BOUNDARY.CITY_ID
    FROM BUSLANES.CITY_BOUNDARIES AS BOUNDARY
    WHERE GEOMETRY.BOUNDARY_ID = BOUNDARY.ID
      AND BOUNDARY.IS_ACTIVE
      AND BOUNDARY.CITY_ID IS NOT NULL
      AND GEOMETRY.CITY_ID IS DISTINCT FROM BOUNDARY.CITY_ID;
END
$FUNCTION$;

SELECT BUSLANES.REBUILD_CITY_BOUNDARY_HIERARCHY();
SELECT BUSLANES.SYNC_ACTIVE_BOUNDARY_CITIES();

