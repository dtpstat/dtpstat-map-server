SET SEARCH_PATH = BUSLANES, PUBLIC;

-- V023 merged unrelated OSM relations solely because their derived names
-- matched. OSM object identity is (osm_type, osm_id); a relation already
-- contains its member ways and must never be merged with another relation by
-- text name.
DROP TRIGGER IF EXISTS CITY_BOUNDARIES_NORMALIZE_RELATIONS
    ON BUSLANES.CITY_BOUNDARIES;
DROP FUNCTION IF EXISTS BUSLANES.NORMALIZE_CITY_BOUNDARY_RELATIONS_TRIGGER();
DROP FUNCTION IF EXISTS BUSLANES.NORMALIZE_CITY_BOUNDARY_RELATIONS();

-- FULL_NAME and its index belonged to the incorrect cross-object grouping
-- model from V023. Source names remain in OSM_NAME/TAGS, while administrator
-- identity is stored explicitly in DISPLAY_NAME/DISPLAY_TYPE below.
DROP INDEX IF EXISTS BUSLANES.CITY_BOUNDARIES_LOGICAL_NAME_IDX;
ALTER TABLE BUSLANES.CITY_BOUNDARIES
    DROP COLUMN IF EXISTS FULL_NAME;

DROP TRIGGER IF EXISTS CITY_BOUNDARIES_SYNC_CITY_FULL_NAME
    ON BUSLANES.CITY_BOUNDARIES;
DROP FUNCTION IF EXISTS BUSLANES.SYNC_CITY_FULL_NAME_FROM_BOUNDARY();

ALTER TABLE BUSLANES.CITY_BOUNDARIES
    DROP CONSTRAINT IF EXISTS CITY_BOUNDARIES_PLACE_TYPE_CHECK,
    ALTER COLUMN PLACE_TYPE DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS ADMIN_LEVEL SMALLINT,
    ADD COLUMN IF NOT EXISTS IS_ACTIVE BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS DISPLAY_NAME TEXT,
    ADD COLUMN IF NOT EXISTS DISPLAY_TYPE TEXT,
    ADD COLUMN IF NOT EXISTS PARENT_ID BIGINT,
    ADD COLUMN IF NOT EXISTS AREA_M2 DOUBLE PRECISION;

UPDATE BUSLANES.CITY_BOUNDARIES
SET ADMIN_LEVEL = CASE
        WHEN TAGS ->> 'admin_level' ~ '^[0-9]+$'
            THEN (TAGS ->> 'admin_level')::SMALLINT
        ELSE NULL
    END,
    DISPLAY_NAME = COALESCE(
        NULLIF(BTRIM(TAGS ->> 'name:ru'), ''),
        NULLIF(BTRIM(OSM_NAME), ''),
        OSM_TYPE || '/' || OSM_ID
    ),
    DISPLAY_TYPE = COALESCE(NULLIF(BTRIM(PLACE_TYPE), ''), 'administrative'),
    AREA_M2 = ST_AREA(GEOM::GEOGRAPHY);

ALTER TABLE BUSLANES.CITY_BOUNDARIES
    ALTER COLUMN DISPLAY_NAME SET NOT NULL,
    ALTER COLUMN DISPLAY_TYPE SET NOT NULL,
    ALTER COLUMN AREA_M2 SET NOT NULL;

ALTER TABLE BUSLANES.CITY_BOUNDARIES
    ADD CONSTRAINT CITY_BOUNDARIES_PLACE_TYPE_CHECK
        CHECK (PLACE_TYPE IS NULL OR PLACE_TYPE IN ('city', 'town')),
    ADD CONSTRAINT CITY_BOUNDARIES_ADMIN_LEVEL_CHECK
        CHECK (ADMIN_LEVEL IS NULL OR ADMIN_LEVEL BETWEEN 1 AND 20),
    ADD CONSTRAINT CITY_BOUNDARIES_DISPLAY_NAME_CHECK
        CHECK (BTRIM(DISPLAY_NAME) <> ''),
    ADD CONSTRAINT CITY_BOUNDARIES_DISPLAY_TYPE_CHECK
        CHECK (BTRIM(DISPLAY_TYPE) <> ''),
    ADD CONSTRAINT CITY_BOUNDARIES_AREA_M2_CHECK
        CHECK (AREA_M2 > 0);

DO $MIGRATION$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM PG_CONSTRAINT
        WHERE CONRELID = 'BUSLANES.CITY_BOUNDARIES'::REGCLASS
          AND CONNAME = 'city_boundaries_parent_id_fkey'
    ) THEN
        ALTER TABLE BUSLANES.CITY_BOUNDARIES
            ADD CONSTRAINT CITY_BOUNDARIES_PARENT_ID_FKEY
                FOREIGN KEY (PARENT_ID)
                REFERENCES BUSLANES.CITY_BOUNDARIES (ID)
                ON DELETE SET NULL;
    END IF;
END
$MIGRATION$;

CREATE INDEX IF NOT EXISTS CITY_BOUNDARIES_PARENT_ID_IDX
    ON BUSLANES.CITY_BOUNDARIES (PARENT_ID);
CREATE INDEX IF NOT EXISTS CITY_BOUNDARIES_ACTIVE_IDX
    ON BUSLANES.CITY_BOUNDARIES (IS_ACTIVE)
    WHERE IS_ACTIVE;
CREATE INDEX IF NOT EXISTS CITY_BOUNDARIES_ADMIN_LEVEL_IDX
    ON BUSLANES.CITY_BOUNDARIES (ADMIN_LEVEL)
    WHERE ADMIN_LEVEL IS NOT NULL;

WITH RANKED AS (
    SELECT
        ID,
        ROW_NUMBER() OVER (
            PARTITION BY
                LOWER(REGEXP_REPLACE(DISPLAY_TYPE, '[[:space:]]+', '', 'g')),
                LOWER(REGEXP_REPLACE(DISPLAY_NAME, '[[:space:]]+', '', 'g'))
            ORDER BY
                (CITY_ID IS NOT NULL) DESC,
                (OSM_TYPE = 'relation') DESC,
                AREA_M2 DESC,
                ID
        ) AS RN
    FROM BUSLANES.CITY_BOUNDARIES
    WHERE PLACE_TYPE IN ('city', 'town')
)
UPDATE BUSLANES.CITY_BOUNDARIES AS BOUNDARY
SET IS_ACTIVE = (RANKED.RN = 1)
FROM RANKED
WHERE RANKED.ID = BOUNDARY.ID;

CREATE UNIQUE INDEX IF NOT EXISTS CITY_BOUNDARIES_ACTIVE_DISPLAY_UNIQUE_IDX
    ON BUSLANES.CITY_BOUNDARIES (
        LOWER(REGEXP_REPLACE(DISPLAY_TYPE, '[[:space:]]+', '', 'g')),
        LOWER(REGEXP_REPLACE(DISPLAY_NAME, '[[:space:]]+', '', 'g'))
    )
    WHERE IS_ACTIVE;

-- Inactive OSM objects may retain their historical city link while another
