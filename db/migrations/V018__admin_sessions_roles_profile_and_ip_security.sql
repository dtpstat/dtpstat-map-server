COMMENT ON TABLE BUSLANES.ADMIN_SESSIONS IS
    'Interactive web-admin sessions. Only SHA-256 token hashes are stored; plaintext tokens exist only in the browser cookie.';
COMMENT ON TABLE BUSLANES.ADMIN_LOGIN_IP_STATE IS
    'Per-IP failed-login counters and temporary throttling state used together with per-account lockout.';
COMMENT ON TABLE BUSLANES.ADMIN_BLOCKED_IPS IS
    'Manual administrator IP blocks with optional expiration and audit provenance.';
